 snapshot TEXT NOT NULL, recorded TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text));
CREATE TABLE IF NOT EXISTS company_modules(company_id BIGINT REFERENCES companies(id), product TEXT REFERENCES products(code),
 module_code TEXT NOT NULL, PRIMARY KEY(company_id,product,module_code));
CREATE TABLE IF NOT EXISTS company_events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id),

CREATE SCHEMA ernasa_control;
SET LOCAL search_path = ernasa_control, pg_catalog;

CREATE TABLE IF NOT EXISTS companies(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, status TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email TEXT UNIQUE NOT NULL, name TEXT NOT NULL, secret TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN ('founder','supervisor','staff')), company_id BIGINT REFERENCES companies,
 active INTEGER NOT NULL DEFAULT 1, CHECK((role='founder')=(company_id IS NULL)));
CREATE UNIQUE INDEX IF NOT EXISTS one_founder ON users(role) WHERE role='founder';
CREATE TABLE IF NOT EXISTS subscriptions(company_id BIGINT PRIMARY KEY REFERENCES companies,
 package TEXT NOT NULL, starts TEXT NOT NULL, ends TEXT NOT NULL, status TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users, csrf TEXT NOT NULL, expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor TEXT NOT NULL, action TEXT NOT NULL,
 company_id BIGINT REFERENCES companies, stamp TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text));
CREATE TABLE IF NOT EXISTS settings(id INTEGER PRIMARY KEY CHECK(id=1), name TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS delegation_limits(company_id BIGINT PRIMARY KEY REFERENCES companies);
CREATE TABLE IF NOT EXISTS staff_subscription_access(user_id BIGINT PRIMARY KEY REFERENCES users);

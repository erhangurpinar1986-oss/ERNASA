CREATE TABLE IF NOT EXISTS company_contacts(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id),
 primary_contact INTEGER NOT NULL DEFAULT 0 CHECK(primary_contact IN (0,1)),
 name TEXT NOT NULL,title TEXT NOT NULL,department TEXT NOT NULL,phone TEXT NOT NULL,email TEXT NOT NULL,kind TEXT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS one_primary_contact ON company_contacts(company_id) WHERE primary_contact=1;
CREATE TABLE IF NOT EXISTS company_addresses(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, company_id BIGINT NOT NULL REFERENCES companies(id),
 kind TEXT NOT NULL,address TEXT NOT NULL,city TEXT NOT NULL,district TEXT NOT NULL,postal TEXT NOT NULL,country TEXT NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS one_core_address ON company_addresses(company_id,kind) WHERE kind IN ('Merkez','Fatura');
